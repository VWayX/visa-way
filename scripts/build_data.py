#!/usr/bin/env python3
"""Build js/data.js from the Passport Index CSV matrix.

Each passport becomes one string with one character per destination
(destinations sorted alphabetically by ISO code):
  v visa required      e e-visa / ETA / visa on arrival
  x no admission       f visa-free, no stay limit listed
  - same country       a..s visa-free, number of days (see DM)
Run:  python scripts/build_data.py
"""
import csv, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
DM = {90: 'a', 30: 'b', 180: 'c', 120: 'd', 60: 'g', 14: 'h', 21: 'i', 360: 'j',
      15: 'k', 42: 'l', 28: 'm', 240: 'n', 45: 'o', 10: 'p', 7: 'q', 150: 'r', 31: 's'}
SCH = "AT BE BG HR CZ DK EE FI FR DE GR HU IS IT LV LI LT LU MT NL NO PL PT RO SK SI ES SE CH AD SM".split()

def enc(v):
    v = v.strip()
    if v == '-1': return '-'
    if v == 'visa required': return 'v'
    if v in ('e-visa', 'eta', 'visa on arrival'): return 'e'
    if v == 'no admission': return 'x'
    if v == 'visa free': return 'f'
    return DM[int(v)]

with open(root / 'data' / 'passport-index-matrix-iso2.csv', newline='', encoding='utf-8') as f:
    rows = list(csv.reader(f))
dest = rows[0][1:]
order = sorted(dest)
idx = [dest.index(c) for c in order]
pw = {r[0]: ''.join(enc(r[1:][i]) for i in idx) for r in rows[1:] if r}
out = ['// Generated by scripts/build_data.py from data/passport-index-matrix-iso2.csv. Do not edit by hand.',
       'const ORD=%s;' % (str(order).replace("'", '"')),
       'const PW={%s};' % ','.join('%s:"%s"' % (p, s) for p, s in sorted(pw.items())),
       'const DM={%s};' % ','.join('%s:%d' % (k, v) for v, k in DM.items()),
       'const SCH=new Set(%s);' % str(SCH).replace("'", '"')]
(root / 'js' / 'data.js').write_text('\n'.join(out) + '\n', encoding='utf-8')
print('passports:', len(pw), 'destinations:', len(order))
